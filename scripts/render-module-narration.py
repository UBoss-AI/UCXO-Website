"""Render UCXO module narration with Heart, aligning each sentence to its visual beat."""
import sys,json,subprocess,re,wave
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'.media-tools'))
import numpy as np
from kokoro_onnx import Kokoro
chapters=json.loads(subprocess.check_output(['node','-e',"process.stdout.write(JSON.stringify(require('./components/story-data.ts').chapters))"],cwd=root))
voice=Kokoro(str(root/'.media-models/kokoro-v1.0.int8.onnx'),str(root/'.media-models/voices-v1.0.bin'))
metadata=[]
pronunciations={'UPingMe':'You Ping Me','UApprove':'You Approve','UMaster':'You Master','UForms':'You Forms','UEngine':'You Engine','URecords':'You Records','UDo':'You Do','UCXO':'U C X O'}
for i,chapter in enumerate(chapters):
    parts=[];points=[];cursor=0
    for cue in chapter['captions']:
        text=cue['text']
        for name,spoken in pronunciations.items():text=text.replace(name,spoken)
        samples,rate=voice.create(text,voice='af_heart',speed=1.0,lang='en-us')
        points.append({'at':round(cursor,3),'storyAt':cue['at']})
        parts.append((np.clip(samples,-1,1)*32767).astype('<i2').tobytes())
        cursor+=len(samples)/rate
        gap=round(.18*rate);parts.append(bytes(gap*2));cursor+=gap/rate
    points.append({'at':round(cursor,3),'storyAt':chapter['duration']})
    with wave.open(str(root/f'public/narration/chapter-{i+1}-heart.wav'),'wb') as out:
        out.setnchannels(1);out.setsampwidth(2);out.setframerate(rate);out.writeframes(b''.join(parts))
    metadata.append({'duration':round(cursor,3),'points':points})
    print(f'Chapter {i+1}: {cursor:.3f}s',flush=True)
old=(root/'components/narration-timing.ts').read_text(encoding='utf-8');helper=old[old.index('export function narrationStoryTime'):]
(root/'components/narration-timing.ts').write_text('// Generated by scripts/render-module-narration.py. Kokoro Heart, local render.\nexport const narrationTiming='+json.dumps(metadata,indent=2)+' as const;\n'+helper,encoding='utf-8')
